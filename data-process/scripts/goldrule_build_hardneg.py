"""困难负样本定向挖掘：从 s3 keep 池按垃圾模式 grep 候选 → LLM 复核打分。

随机分层抽不出语义垃圾（keep 池 S1 已滤形式垃圾 + 上游已筛），负样本要从
模式富集区定向挖：web=SEO/spinner 话术、chinese=软文推广、code=脚手架/死码。
产出追加进 annotate 队列（同 rubric 标注），目标补 400-600 条低分样本。
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq

PATTERNS = {
    "web": [
        re.compile(r"(?i)(best|top|cheap)\s+\w+\s+(vpn|hosting|casino|loan|insurance)"),
        re.compile(r"(?i)(click here|buy now|limited time offer|special discount|for the purpose of)"),
        re.compile(r"(?i)affiliate|sponsored (post|content)|promo code"),
    ],
    "chinese": [
        re.compile(r"(医院|专家指出|治愈|挂号|在线咨询|权威疗法)"),
        re.compile(r"(装修公司|装修知识|请关注我们的|每天更新)"),
        re.compile(r"(品牌|厂家直销|价格优惠|欢迎咨询|服务热线|领先水平)"),
        re.compile(r"(点击链接|扫码关注|领取优惠|限时特价|免费领取)"),
    ],
    "code": [
        re.compile(r"(?i)TODO: implement|NotImplementedError|pass\s*#\s*placeholder"),
        re.compile(r"(?i)auto[- ]generated|do not edit|generated by"),
    ],
}
QUOTA = {"web": 300, "chinese": 300, "code": 100}
SRC = {
    "web": ["fineweb", "dclm-baseline"],
    "chinese": ["skypile-150b", "cci3-hq"],
    "code": ["github-code", "starcoderdata"],
}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--processed-root", default="../data/processed")
    ap.add_argument("--out", default="../data/models/goldrule/hard_neg_set.parquet")
    ap.add_argument("--max-chars", type=int, default=3000)
    ap.add_argument("--seed", default="goldrule-hardneg-v1")
    args = ap.parse_args(argv)
    out_root = Path(args.processed_root).resolve()
    from yuformer_data.scale.rule_score import rule_score

    rows = []
    for domain, pats in PATTERNS.items():
        quota = QUOTA[domain]
        pool = []
        for src in SRC[domain]:
            src_dir = out_root / "s3" / src
            if not src_dir.is_dir():
                continue
            files = sorted(src_dir.rglob("*.parquet"))
            for f in files[:: max(1, len(files) // 6)][:6]:
                try:
                    pf = pq.ParquetFile(f)
                except Exception:
                    continue
                for batch in pf.iter_batches(batch_size=1024, columns=["doc_id", "text", "lang", "s2_decision"]):
                    for r in batch.to_pylist():
                        if r["s2_decision"] != "keep" or not r["text"] or len(r["text"]) < 200:
                            continue
                        hits = sum(len(p.findall(r["text"][:4000])) for p in pats)
                        if hits >= 2:
                            pool.append((r["doc_id"], r["text"], r["lang"], src, hits))
                    if len(pool) >= quota * 5:
                        break
                if len(pool) >= quota * 5:
                    break
            if len(pool) >= quota * 5:
                break
        pool.sort(key=lambda x: -x[4])
        step = max(1, len(pool) // quota)
        picked = pool[::step][:quota]
        for d, t, lang, src, hits in picked:
            rows.append((d, domain, lang, t[: args.max_chars], len(t), rule_score(t[:8192]), src))
        print(f"[ok] {domain}: pool={len(pool)} picked={len(picked)}", file=sys.stderr)

    table = pa.table(
        {
            "doc_id": [r[0] for r in rows],
            "domain": [r[1] for r in rows],
            "lang": [r[2] for r in rows],
            "text": [r[3] for r in rows],
            "full_chars": [r[4] for r in rows],
            "rule_score": [r[5] for r in rows],
            "source": [r[6] for r in rows],
        }
    )
    out = Path(args.out)
    pq.write_table(table, out, compression="zstd")
    print(json.dumps({"rows": len(rows), "out": str(out)}, sort_keys=True))


if __name__ == "__main__":
    sys.exit(main())
