FROZEN = ROOT / "experiments/e4_curriculum/results/frozen_1t_recipe.json"
CONFIG = ROOT / "pretrain/configs/production_canary/production_8gpu.yaml"
ENV = ROOT / "pretrain/configs/production_canary/production_8gpu.env"
