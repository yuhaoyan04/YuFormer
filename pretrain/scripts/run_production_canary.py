DEFAULT_MAX_DAYS = 33.0


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def atomic_text(path: Path, value: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    temporary.write_text(value, encoding="utf-8")
    os.replace(temporary, path)


def load_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"expected JSON object: {path}")
    return value


def validate_hash_manifest(root: Path, manifest: Any, label: str) -> None:
    if not isinstance(manifest, dict) or not manifest:
        raise ValueError(f"{label} hash manifest is absent")
    for recorded, expected in manifest.items():
        if not isinstance(recorded, str) or not isinstance(expected, str):
            raise ValueError(f"{label} hash manifest is malformed")
        path = Path(recorded)
        if not path.is_absolute():
            path = root / path
        if not path.is_file() or sha256(path) != expected:
            raise ValueError(f"{label} drift: {recorded}")


def validate_frozen_bindings(root: Path, frozen: dict[str, Any]) -> None:
    freeze_tool = root / "experiments/e4_curriculum/scripts/freeze_1t_recipe.py"
    if frozen.get("freeze_tool_sha256") != sha256(freeze_tool):
        raise ValueError("frozen recipe was generated by a stale freeze tool")
    validate_hash_manifest(root, frozen.get("inputs"), "frozen input")
    validate_hash_manifest(root, frozen.get("outputs"), "frozen output")
    identity_path = root / "report/experiment_identity_audit_latest.json"
    identity = load_json(identity_path)
    if (identity.get("status") != "PASS"
            and not identity_exception_is_bound(root, frozen, identity)):
        raise ValueError("experiment identity audit is neither PASS nor covered by the explicit E1 waiver")
    snapshot = identity.get("evidence_snapshot")
    if identity.get("evidence_snapshot_count") != (
            len(snapshot) if isinstance(snapshot, dict) else -1):
        raise ValueError("experiment identity evidence snapshot count is inconsistent")
    validate_hash_manifest(root, snapshot, "experiment identity evidence")


def build_contract(root: Path) -> dict[str, Any]:
    frozen_path = root / FROZEN.relative_to(ROOT)
    frozen = load_json(frozen_path)
    if frozen.get("status") != "PASS":
        raise ValueError("frozen production recipe is not PASS")
    validate_frozen_bindings(root, frozen)
    authorization = load_authorization(root)
    base = yaml.safe_load((root / "pretrain/configs/pretrain_base.yaml").read_text(encoding="utf-8"))
    production_env = _parse_env(root/'pretrain/configs/pretrain_base.env')
    config, probe_identity = build_probe(root, base, production_env, role='canary', publish=True)
    config["run_name"] = "production_8gpu_canary"
    if int(config["parallel"]["world_size"]) != WORLD_SIZE:
        raise ValueError("production canary requires the eight-GPU production contract")
    config["out_dir"] = "${YUFORMER_PRETRAIN_OUT}"
    config["model"]["configs"] = "${YUFORMER_MODEL_CONFIGS}"
    tokens_per_step = (int(config["data"]["seq_len"])
                       * int(config["train"]["micro_batch_size"])
                       * int(config["train"]["grad_accum"])
                       * int(config["parallel"]["world_size"]))
    if tokens_per_step != int(frozen.get("selected_tokens_per_step", -1)):
        raise ValueError("production config does not implement the frozen batch selection")
    config["optim"].update({"lr_schedule": "cosine", "warmup_steps": 10,
                            "min_lr_ratio": 0.1})
    config["optim"].pop("decay_steps", None)
    config["train"].update({
        "budget_tokens": STEPS * tokens_per_step, "expected_iters": STEPS,
        "eval_every": 100, "log_every": 10, "save_every": 100,
        "keep_last_n": 2, "keep_every": 1000,
    })
    config_path = root / CONFIG.relative_to(ROOT)
    env_path = root / ENV.relative_to(ROOT)
    atomic_text(config_path, yaml.safe_dump(config, sort_keys=False, allow_unicode=True))
    values = dict(production_env)
    values.update({
        "YUFORMER_PYTHON": str(PYTHON),
        "YUFORMER_TORCHTITAN_ROOT": "/opt/torchtitan-v0.3.0",
        "YUFORMER_CONFIG": "configs/production_canary/production_8gpu.yaml",
        "GPUS_PER_NODE": str(WORLD_SIZE), "MASTER_PORT": "29800",
        "CUDA_VISIBLE_DEVICES": ",".join(str(index) for index in range(WORLD_SIZE)),
        "YUFORMER_MODEL_CONFIGS": str(root / "model/configs/pretrain_final_model_configs.yaml"),
        "YUFORMER_PRETRAIN_OUT": str(root / RUN_DIR.relative_to(ROOT)),
        "OMP_NUM_THREADS": "1", "TORCHINDUCTOR_COMPILE_THREADS": "2",
    })
    atomic_text(env_path, "".join(f"{key}={value}\n" for key, value in values.items()))
    sys.path.insert(0, str(root/'experiments/e4_curriculum/scripts'))
    from total_budget_contract import load_total_budget_contract
    plan = yaml.safe_load((root/'experiments/e4_curriculum/configs/e4_1t_wsd_context.yaml').read_bytes())
    total = load_total_budget_contract(root, plan)
    if frozen.get('training_adoption', {}).get('global_training_budget') is not None and total is None:
        raise ValueError('frozen whole-chain training needs its bound exact total allocation')
    result = {
        "qualification_identity": qualification_identity(root),
        "runner_tool_sha256": sha256(Path(__file__)),
        "frozen_recipe_sha256": sha256(frozen_path),
        "config_sha256": sha256(config_path), "env_sha256": sha256(env_path),
        "tokens_per_step": tokens_per_step, "steps": STEPS,
        "world_size": WORLD_SIZE,
        "production_probe": probe_identity,
        "planned_training_duty_cycle": float(authorization["training"].get(
            "planned_training_duty_cycle", 0.90)),
        "maximum_projected_days": float(authorization["training"].get(
            "launch_runtime_ceiling_days", DEFAULT_MAX_DAYS)),
        "target_completion_days": float(authorization["training"].get(
            "target_completion_days", 30.0)),
    }
    if total is not None:
        result['full_chain_runtime'] = {'budget': total['budget'], 'measurements': total['measurements'],
                                       'source_inputs': total['inputs']}
    return result


def evaluate_result(result: dict[str, Any], contract: dict[str, Any]) -> dict[str, Any]:
    issues: list[str] = []
    if result.get("status") != "PASS":
        issues.append("result_not_pass")
    hyper = result.get("hyperparameters") or {}
    if "world_size" in contract and hyper.get("world_size") != contract["world_size"]:
        issues.append("world_size_mismatch")
    if hyper.get("tokens_per_step") != contract["tokens_per_step"]:
        issues.append("tokens_per_step_mismatch")
    if hyper.get("trained_steps") != contract["steps"]:
        issues.append("trained_steps_mismatch")
    if hyper.get("trained_tokens") != contract["steps"] * contract["tokens_per_step"]:
        issues.append("trained_tokens_mismatch")
    tps = [float(row["value"]) for row in (result.get("series") or {}).get("throughput(tps)", [])
           if isinstance(row.get("value"), (int, float)) and math.isfinite(float(row["value"]))
           and float(row["value"]) > 0]
    steady = tps[len(tps) // 4:]
    if len(steady) < 10:
        issues.append("insufficient_steady_throughput_points")
        conservative_tps = median_tps = None
    else:
        ordered = sorted(steady)
        conservative_tps = ordered[max(0, math.ceil(0.10 * len(ordered)) - 1)]
        median_tps = statistics.median(steady)
    mfu = [float(row["value"]) for row in (result.get("series") or {}).get("mfu(%)", [])
           if isinstance(row.get("value"), (int, float)) and math.isfinite(float(row["value"]))]
    median_mfu = statistics.median(mfu[len(mfu) // 4:]) if mfu else None
    world_size = int(contract.get("world_size", WORLD_SIZE))
    duty_cycle = float(contract.get("planned_training_duty_cycle", 1.0))
    if world_size < 1 or not math.isfinite(duty_cycle) or not 0 < duty_cycle <= 1:
        raise ValueError("invalid canary topology or training duty cycle")
    projected_training_days = (TARGET_TOKENS / (world_size * conservative_tps * 86400)
                      if conservative_tps else None)
    projected_days = projected_training_days / duty_cycle if projected_training_days else None
    total_days = projected_days
    stage_forecasts = []
    whole_chain = contract.get('full_chain_runtime')
    if whole_chain is not None:
        budget, measurements = whole_chain['budget'], whole_chain['measurements']
        expected = [('4k-pretrain',4096),('16k-midtrain',16384),('64k-midtrain',65536)]
        if (budget.get('world_size') != world_size or world_size != 8
                or [(s.get('name'),s.get('seq_len')) for s in budget.get('stages',[])] != expected
                or sum(s['tokens'] for s in budget['stages']) != budget['actual_total_tokens']
                or set(measurements) != {name for name,_ in expected}
                or any(measurements[name].get('world_size')!=8 or measurements[name].get('seq_len')!=seq
                       or measurements[name].get('parameters')!=budget.get('parameters') for name,seq in expected)):
            raise ValueError('canary whole-chain allocation does not close its fixed stage budget')
        for stage in budget['stages']:
            rate = conservative_tps if stage['seq_len']==4096 else measurements[stage['name']]['p10_tps_per_device']
            if rate is None:
                total_days = None
                break
            if type(rate) not in (int,float) or not math.isfinite(rate) or rate<=0:
                raise ValueError('canary whole-chain stage throughput must be finite and positive')
            days = stage['tokens']/(world_size*rate*duty_cycle*86400)
            stage_forecasts.append({'name':stage['name'],'tokens':stage['tokens'],
                                    'p10_tps_per_device':rate,'days':days})
        else:
            total_days = sum(stage['days'] for stage in stage_forecasts)
    maximum_days = float(contract.get("maximum_projected_days", DEFAULT_MAX_DAYS))
    if not math.isfinite(maximum_days) or maximum_days <= 0:
        raise ValueError("invalid maximum projected runtime")
    if total_days is None or total_days > maximum_days:
        issues.append('projected_total_runtime_exceeds_authorized_ceiling' if whole_chain is not None
                      else 'projected_1t_runtime_exceeds_authorized_ceiling')
    return {
        "status": "PASS" if not issues else "FAIL", "issues": issues,
        "steady_points": len(steady), "median_tps_per_device": median_tps,
        "p10_tps_per_device": conservative_tps, "median_mfu_pct": median_mfu,
        "projected_1t_days_from_p10": projected_days,
        "projected_training_days_from_p10": projected_training_days,
        'projected_total_training_days': total_days,
        'runtime_scope': 'TOTAL_4K_16K_64K' if whole_chain is not None else 'LEGACY_1T_4K_PROXY',
        'stage_forecasts': stage_forecasts,
        "planned_training_duty_cycle": duty_cycle,
        "maximum_days": maximum_days,
        "target_completion_days": contract.get("target_completion_days", 30.0),
        "world_size": world_size,
    }


def launch_environment(root: Path) -> tuple[dict[str, str], list[int]]:
    devices = sorted(allowed_gpu_indices(root / 'data/health'))
    if len(devices) < WORLD_SIZE:
        raise ValueError('Production canary requires eight authorized GPU devices')
    devices = devices[:WORLD_SIZE]
    env = dict(os.environ)
    env['CUDA_VISIBLE_DEVICES'] = ','.join(map(str, devices))
    return env, devices


def run(root: Path) -> dict[str, Any]:
    launch_env, devices = launch_environment(root)
    contract = build_contract(root)
    qualification = load_json(root / "data/health/torchtitan-qualification.json")
    if qualification.get("status") != "PASS" or not report_matches(
            qualification, contract["qualification_identity"]):
        raise ValueError("production canary requires current GPU qualification PASS")
    if qualification.get("stages", {}).get("reshard_4to8", {}).get("status") != "PASS":
        raise ValueError("eight-GPU canary requires 4-to-8 reshard qualification PASS")
    contract['gpu_indices'] = devices
    prior = {}
    report_path = root / REPORT.relative_to(ROOT)
    if report_path.is_file():
        try:
            prior = load_json(report_path)
        except (OSError, ValueError):
            pass
    run_dir = root / RUN_DIR.relative_to(ROOT)
    if run_dir.exists() and (
            prior.get("frozen_recipe_sha256") != contract["frozen_recipe_sha256"]
            or not report_matches(prior, contract["qualification_identity"])
            or prior.get("runner_tool_sha256") != contract["runner_tool_sha256"]
            or prior.get("config_sha256") != contract["config_sha256"]
            or prior.get("env_sha256") != contract["env_sha256"]):
        archive = run_dir.parent / "_stale"
        archive.mkdir(parents=True, exist_ok=True)
        target = archive / f"{run_dir.name}-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')}"
        move_artifact(run_dir, target)
    atomic_text(report_path, json.dumps({"schema_version": 1, "status": "IN_PROGRESS",
                                         **contract}, indent=2, sort_keys=True) + "\n")
    completed = subprocess.run(["bash", str(root / LAUNCH.relative_to(ROOT)),
                                str(root / ENV.relative_to(ROOT))], cwd=root, env=launch_env)
    if completed.returncode:
        return {"schema_version": 1, "status": "FAIL", "observed_at": now_iso(),
                "reason": "launch_failed", "returncode": completed.returncode, **contract}
    collected = subprocess.run([str(PYTHON), str(root / COLLECT.relative_to(ROOT)), str(run_dir)],
                               cwd=root, capture_output=True, text=True)
    result = load_json(run_dir / "result.json") if (run_dir / "result.json").is_file() else {}
    evaluation = evaluate_result(result, contract)
    if qualification_identity(root) != contract["qualification_identity"]:
        evaluation["status"] = "FAIL"
        evaluation["issues"].append("qualification_inputs_changed_during_canary")
    return {"schema_version": 1, "status": evaluation["status"], "observed_at": now_iso(),
            **contract, "result_sha256": sha256(run_dir / "result.json") if result else None,
            "identity_sha256": result.get("identity_sha256"),
            "collect_returncode": collected.returncode, "evaluation": evaluation}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, default=REPORT)
    parser.add_argument("--prepare-only", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        if args.prepare_only:
            result = {"schema_version": 1, "status": "PREPARED", **build_contract(root)}
        else:
            result = run(root)
    except Exception as exc:
        result = {"schema_version": 1, "status": "FAIL", "observed_at": now_iso(),
                  "reason": f"{type(exc).__name__}: {exc}"}
    output = args.output if args.output.is_absolute() else root / args.output
    atomic_text(output, json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": result["status"],
                      "projected_days": (result.get("evaluation") or {}).get(
                          "projected_total_training_days",
                          (result.get("evaluation") or {}).get("projected_1t_days_from_p10"))}, sort_keys=True))
    return 0 if result["status"] in {"PASS", "PREPARED"} else 1


if __name__ == "__main__":
    raise SystemExit(main())
